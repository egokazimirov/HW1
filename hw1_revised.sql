-- ЗАДАНИЕ Е1
-- Исходный запрос (выполнить и посмотреть результат):
SELECT v.professional_role,
count(*) AS vacancies,
sum(v.salary_from) AS total_salary,
count(r.response_id) / count(*) AS responses_per_vacancy
FROM vacancies v
JOIN responses r ON v.vacancy_id = r.vacancy_id
WHERE v.closed_at = NULL
GROUP BY 1;

-- Ошибки (минимум четыре):
-- 1. Написано WHERE v.closed_at = NULL. Из-за этого запрос выдал 0 строк, 
-- потому что сравнение с NULL ничего не возвращает.
-- 2. Использован INNER JOIN, поэтому из выборки пропадут все вакансии 
-- на которые еще никто не откликнулся.
-- 3. Кол-во вакансий считается через count(*) и поэтому функция посчитает не вакансии, а количество откликов. 
-- Нужно использовать count(DISTINCT v.vacancy_id).
-- 4. count(r.response_id) / count(*) - это деление целых чисел. В базе оно даст 0. 
-- Нужно умножить на 1.0, чтобы получить дробное число.
-- 5. sum(v.salary_from) считается неправильно, потму что после JOIN зарплата одной вакансии 
-- повторяется столько раз, сколько у нее откликов. Лучше использовать ROUND(AVG(v.salary_from)) - среднюю 
-- зарплату по вакансиям, так как отклики на нее не влияют.

-- Исправленный запрос:
SELECT 
    v.professional_role, 
    count(DISTINCT v.vacancy_id) AS vacancies, 
    round(AVG(v.salary_from)) AS avg_salary, 
    round(1.0 * count(r.response_id) / NULLIF(count(DISTINCT v.vacancy_id), 0), 2) AS responses_per_vacancy
FROM vacancies v 
LEFT JOIN responses r ON v.vacancy_id = r.vacancy_id 
WHERE v.closed_at IS NULL 
GROUP BY v.professional_role;

-- Какие два правила из лекции защитили бы от этих ошибок при написании запроса:
-- 1. Не забывать про NULL. Для проверки на пустые значения использовать 
-- только IS NULL или IS NOT NULL, никогда не писать = NULL.
-- 2. Всегда держать в голове гранулярность строк после JOIN. Если мы 
-- джойним таблицу, где на одну строку слева может быть много строк справа, 
-- то считать сами объекты слева нужно строго через COUNT(DISTINCT колонка). 
-- Иначе база посчитает не вакансии, а каждый отклик на вакансию, и все цифры размножатся.